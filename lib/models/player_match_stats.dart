class PlayerMatchStats {
  // ==========================================================
  // WYSTĘPY
  // ==========================================================

  int appearances = 0;
  int starts = 0;
  int substituteAppearances = 0;

  int minutes = 0;

  // ==========================================================
  // GOLE / ASYSTY
  // ==========================================================

  int goals = 0;
  int assists = 0;

  // ==========================================================
  // KARTKI
  // ==========================================================

  int yellowCards = 0;
  int redCards = 0;

  // ==========================================================
  // STRZAŁY
  // ==========================================================

  int shots = 0;
  int shotsOnTarget = 0;

  // ==========================================================
  // GRA
  // ==========================================================

  int keyPasses = 0;
  int successfulDribbles = 0;

  // ==========================================================
  // OCENA
  // ==========================================================

  double averageRating = 0.0;

  // ==========================================================
  // DODANIE WYSTĘPU
  // ==========================================================

  void addAppearance({
    required int playedMinutes,
    required bool started,
    required double rating,
  }) {
    appearances++;

    if (started) {
      starts++;
    } else {
      substituteAppearances++;
    }

    minutes += playedMinutes;

    final totalRating =
        averageRating * (appearances - 1);

    averageRating =
        (totalRating + rating) / appearances;
  }

  // ==========================================================
  // DODANIE GOLA
  // ==========================================================

  void addGoal() {
    goals++;
  }

  // ==========================================================
  // DODANIE ASYSTY
  // ==========================================================

  void addAssist() {
    assists++;
  }

  // ==========================================================
  // STRZAŁ
  // ==========================================================

  void addShot({
    required bool onTarget,
  }) {
    shots++;

    if (onTarget) {
      shotsOnTarget++;
    }
  }

  // ==========================================================
  // KLUCZOWE PODANIE
  // ==========================================================

  void addKeyPass() {
    keyPasses++;
  }

  // ==========================================================
  // UDANY DRYBLING
  // ==========================================================

  void addSuccessfulDribble() {
    successfulDribbles++;
  }

  // ==========================================================
  // ŻÓŁTA KARTKA
  // ==========================================================

  void addYellowCard() {
    yellowCards++;
  }

  // ==========================================================
  // CZERWONA KARTKA
  // ==========================================================

  void addRedCard() {
    redCards++;
  }
}
